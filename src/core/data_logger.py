"""
Diagnostic Data Logger Module.

Records timestamped gaze tracking samples, raw ocular features, baseline deviations,
head pose orientation, and classification telemetry to CSV for algorithmic evaluation.
"""

import csv
from datetime import datetime
import logging
from pathlib import Path
import time
from typing import Optional

logger = logging.getLogger(__name__)


class DiagnosticDataLogger:
    """
    Lightweight CSV logger for gaze tracking diagnostics and evaluation.
    """

    HEADERS = [
        "timestamp",
        "frame_idx",
        "tracking_state",
        "face_detected",
        "r_iris_x",
        "r_iris_y",
        "l_iris_x",
        "l_iris_y",
        "raw_x",
        "raw_y",
        "smoothed_x",
        "smoothed_y",
        "baseline_x",
        "baseline_y",
        "delta_x",
        "delta_y",
        "direction",
        "confidence",
        "yaw",
        "pitch",
        "roll",
        "r_openness",
        "l_openness",
        "v_state",
    ]

    def __init__(self, output_dir: Optional[Path] = None) -> None:
        """
        Initialize the data logger.

        Args:
            output_dir: Directory where CSV files are saved (defaults to cv-service/logs).
        """
        self.output_dir = output_dir or (Path(__file__).resolve().parent.parent.parent / "logs")
        self._is_logging = False
        self._file_handle = None
        self._csv_writer = None
        self._current_path: Optional[Path] = None
        self._record_count = 0

    @property
    def is_logging(self) -> bool:
        """True if data is actively being written to disk."""
        return self._is_logging

    @property
    def record_count(self) -> int:
        """Number of records written in the current logging session."""
        return self._record_count

    @property
    def current_file(self) -> Optional[Path]:
        """Path to active CSV file."""
        return self._current_path

    def start_logging(self, filename: Optional[str] = None) -> Path:
        """
        Begin a new diagnostic data collection session.

        Args:
            filename: Custom filename (or autogenerated with timestamp).

        Returns:
            Path of the opened CSV file.
        """
        if self._is_logging:
            logger.warning("DiagnosticDataLogger is already logging.")
            assert self._current_path is not None
            return self._current_path

        self.output_dir.mkdir(parents=True, exist_ok=True)
        if filename is None:
            ts_str = datetime.now().strftime("%Y%m%d_%H%M%S")
            filename = f"gaze_diagnostic_{ts_str}.csv"

        self._current_path = self.output_dir / filename
        self._file_handle = open(self._current_path, mode="w", newline="", encoding="utf-8")
        self._csv_writer = csv.writer(self._file_handle)
        self._csv_writer.writerow(self.HEADERS)
        self._file_handle.flush()

        self._is_logging = True
        self._record_count = 0
        logger.info(f"Started diagnostic gaze logging to {self._current_path}")
        return self._current_path

    def log_frame(
        self,
        frame_idx: int,
        tracking_state: str,
        face_detected: bool,
        r_iris_x: Optional[float],
        r_iris_y: Optional[float],
        l_iris_x: Optional[float],
        l_iris_y: Optional[float],
        raw_x: Optional[float],
        raw_y: Optional[float],
        smoothed_x: Optional[float],
        smoothed_y: Optional[float],
        baseline_x: float,
        baseline_y: float,
        delta_x: Optional[float],
        delta_y: Optional[float],
        direction: str,
        confidence: float,
        yaw: Optional[float] = None,
        pitch: Optional[float] = None,
        roll: Optional[float] = None,
        r_openness: Optional[float] = None,
        l_openness: Optional[float] = None,
        v_state: Optional[str] = None,
    ) -> None:
        """Write a single frame sample to the active CSV file."""
        if not self._is_logging or self._csv_writer is None:
            return

        def fmt(val: Optional[float], dec: int = 4) -> str:
            return f"{val:.{dec}f}" if val is not None else ""

        row = [
            f"{time.time():.4f}",
            frame_idx,
            tracking_state,
            1 if face_detected else 0,
            fmt(r_iris_x),
            fmt(r_iris_y),
            fmt(l_iris_x),
            fmt(l_iris_y),
            fmt(raw_x),
            fmt(raw_y),
            fmt(smoothed_x),
            fmt(smoothed_y),
            fmt(baseline_x),
            fmt(baseline_y),
            fmt(delta_x),
            fmt(delta_y),
            direction,
            fmt(confidence, 3),
            fmt(yaw, 2),
            fmt(pitch, 2),
            fmt(roll, 2),
            fmt(r_openness, 3),
            fmt(l_openness, 3),
            v_state or "",
        ]
        self._csv_writer.writerow(row)
        self._record_count += 1
        if self._record_count % 30 == 0 and self._file_handle:
            self._file_handle.flush()

    def stop_logging(self) -> Optional[Path]:
        """Stop logging and flush the file handle."""
        if not self._is_logging:
            return None

        saved_path = self._current_path
        if self._file_handle:
            try:
                self._file_handle.flush()
                self._file_handle.close()
            except Exception as e:
                logger.warning(f"Error closing CSV log file: {e}")
            finally:
                self._file_handle = None
                self._csv_writer = None

        self._is_logging = False
        logger.info(f"Stopped diagnostic logging. Saved {self._record_count} records to {saved_path}")
        return saved_path

    def toggle_logging(self, filename: Optional[str] = None) -> bool:
        """
        Toggle logging session on or off.

        Returns:
            True if logging is now active, False if stopped.
        """
        if self._is_logging:
            self.stop_logging()
            return False
        else:
            self.start_logging(filename)
            return True
